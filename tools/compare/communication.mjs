// Per-issue upstream communication tracking. Technical results stay in EVIDENCE.md/feedback.json; this file records whether a
// significant finding has a draft, has been posted, was addressed independently, or needs a human decision. Nothing here
// posts, comments or changes an issue. See docs/COMMUNICATION.md.
import fs from 'node:fs';
import path from 'node:path';
import { validateAgainst } from '../observability/schema.mjs';

export const STATES = ['new', 'draft-prepared', 'awaiting-human-review', 'ready-to-post', 'posted', 'independently-addressed', 'superseded', 'withdrawn', 'no-upstream-communication'];
export const ACTIONABLE = new Set(['new', 'draft-prepared', 'awaiting-human-review', 'ready-to-post']);
export const DISCOVERED_BY = ['human', 'ai', 'joint', 'unknown'];
export const SCHEMA_PATH = path.join(path.dirname(new URL(import.meta.url).pathname), 'communication.schema.json');
const schema = JSON.parse(fs.readFileSync(SCHEMA_PATH, 'utf8'));
const today = () => new Date().toISOString().slice(0, 10);

export const normalizeEntry = (entry) => ({
  ...entry,
  id: String(entry.id || ''),
  summary: String(entry.summary || ''),
  state: entry.state ?? 'new',
  discovered: {
    by: DISCOVERED_BY.includes(entry.discovered?.by) ? entry.discovered.by : 'unknown',
    date: entry.discovered?.date || today(),
    note: entry.discovered?.note ?? null,
  },
  tested_revision: entry.tested_revision ?? null,
  evidence: Array.isArray(entry.evidence) ? entry.evidence.map(String) : [],
  draft: entry.draft ?? null,
  posted: entry.posted ? { url: entry.posted.url ?? null, date: entry.posted.date ?? null } : null,
  independently_addressed: entry.independently_addressed ? { by: entry.independently_addressed.by ?? null, url: entry.independently_addressed.url ?? null, date: entry.independently_addressed.date ?? null } : null,
  superseded_by: entry.superseded_by ?? null,
  decisions: Array.isArray(entry.decisions) ? entry.decisions.map(String) : [],
  updated: entry.updated || today(),
  history: Array.isArray(entry.history) ? entry.history : [],
});

export const normalizeFile = (file, issue = file?.issue) => ({ schemaVersion: 1, issue: String(issue || ''), entries: (file?.entries || []).map(normalizeEntry) });

export function validateFile(file) {
  return validateAgainst(normalizeFile(file), schema);
}

export function readCommunication(root, nid) {
  const file = path.join(root, 'reports/issues', String(nid), 'communication.json');
  try { return normalizeFile(JSON.parse(fs.readFileSync(file, 'utf8')), nid); } catch { return normalizeFile({ entries: [] }, nid); }
}

export function communicationPath(root, nid) { return path.join(root, 'reports/issues', String(nid), 'communication.json'); }

export function writeCommunication(root, nid, file) {
  const normalized = normalizeFile(file, nid);
  const check = validateFile(normalized);
  if (!check.ok) throw new Error(`refusing to write communication.json for #${nid}: ${check.errors.slice(0, 6).map((e) => `${e.path || '/'} ${e.message}`).join('; ')}`);
  const target = communicationPath(root, nid);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, `${JSON.stringify(normalized, null, 2)}\n`);
  return normalized;
}

export const needsUpdate = (entry) => ACTIONABLE.has(entry.state);

export const rows = (files) => files.flatMap(({ issue, file }) => file.entries.map((entry) => ({ issue, ...entry }))).sort((a, b) => Number(needsUpdate(b)) - Number(needsUpdate(a)) || Number(a.issue) - Number(b.issue) || a.id.localeCompare(b.id));

export function issueMarkdown(issue, file) {
  const entries = file.entries;
  let md = `# Upstream communication — #${issue}\n\nGenerated by \`node scripts/communication.mjs list ${issue}\`; do not edit by hand. This is communication state, not a test verdict. Nothing here is posted automatically.\n\n`;
  const pending = entries.filter(needsUpdate).length;
  md += `${entries.length} finding(s), ${pending} needing a next human step.\n\n`;
  if (!entries.length) return `${md}No findings have been recorded yet. Add one with \`node scripts/communication.mjs add ${issue} --summary "..." --discovered-by human|ai|joint\`.\n`;
  md += `| ID | State | Finding | Tested revision | Draft | Posted | Decision |\n|---|---|---|---|---|---|---|\n`;
  for (const e of entries) {
    const cell = (v) => String(v ?? '—').replace(/\|/g, '\\|').replace(/\n/g, ' ');
    const posted = e.posted?.url ? `[posted](${e.posted.url})` : (e.posted ? 'posted (no URL)' : '—');
    md += `| ${e.id} | ${e.state} | ${cell(e.summary)} | ${cell(e.tested_revision)} | ${cell(e.draft)} | ${posted} | ${cell(e.decisions.join('; '))} |\n`;
  }
  return md;
}

export function aggregateMarkdown(files) {
  const all = rows(files);
  let md = `# Upstream communication — all issues\n\nGenerated by \`node scripts/communication.mjs list --all\`; do not edit by hand. Communication state is separate from technical test results, and nothing here is posted automatically.\n\n`;
  const pending = all.filter(needsUpdate);
  md += `${all.length} finding(s) across ${new Set(all.map((x) => x.issue)).size} issue(s); **${pending.length} need a next human step**.\n\n`;
  if (!all.length) return `${md}No findings have been recorded yet. Use \`node scripts/communication.mjs add <nid> --summary "..." --discovered-by human|ai|joint\`.\n`;
  md += `## Needs an update\n\n| Issue | ID | State | Finding | Tested revision | Posted | Decision |\n|---|---|---|---|---|---|---|\n`;
  for (const e of pending) md += `| [#${e.issue}](issues/${e.issue}/SUMMARY.md) | ${e.id} | ${e.state} | ${e.summary.replace(/\|/g, '\\|')} | ${e.tested_revision || '—'} | ${e.posted?.url ? `[posted](${e.posted.url})` : '—'} | ${(e.decisions.join('; ') || '—').replace(/\|/g, '\\|')} |\n`;
  const rest = all.filter((e) => !needsUpdate(e));
  if (rest.length) {
    md += `\n## Closed or not requiring action\n\n| Issue | ID | State | Finding | Posted / addressed |\n|---|---|---|---|---|\n`;
    for (const e of rest) md += `| #${e.issue} | ${e.id} | ${e.state} | ${e.summary.replace(/\|/g, '\\|')} | ${e.posted?.url || e.independently_addressed?.url || e.superseded_by || '—'} |\n`;
  }
  return md;
}
