// Structured human/AI contribution history for one issue. Curated by a person or an agent, never inferred from commit
// authorship. It records the original human idea, what AI added or got wrong, human corrections, rejected approaches and
// independent verification. Nothing here is posted anywhere.
import fs from 'node:fs';
import path from 'node:path';
import { validateAgainst } from '../observability/schema.mjs';

export const KINDS = ['human-origin', 'inherited-decision', 'ai-addition', 'ai-test-discovery', 'human-correction', 'rejected-ai-approach', 'human-decision', 'independent-verification', 'uncertainty'];
export const SCHEMA_PATH = path.join(path.dirname(new URL(import.meta.url).pathname), 'contributions.schema.json');
const schema = JSON.parse(fs.readFileSync(SCHEMA_PATH, 'utf8'));
const today = () => new Date().toISOString().slice(0, 10);

export const SECTION = {
  'human-origin': 'Original human contributions',
  'inherited-decision': 'Technical decisions inherited',
  'ai-addition': 'AI-generated additions',
  'ai-test-discovery': 'Problems found through AI-assisted testing',
  'human-correction': 'Human corrections to AI-generated work',
  'rejected-ai-approach': 'AI-generated approaches rejected',
  'human-decision': 'Human decisions that shaped the implementation',
  'independent-verification': 'Independent human verification',
  'uncertainty': 'Remaining uncertainties',
};
export const ORDER = ['human-origin', 'inherited-decision', 'ai-addition', 'ai-test-discovery', 'human-correction', 'rejected-ai-approach', 'human-decision', 'independent-verification', 'uncertainty'];

export const normalizeEntry = (entry = {}) => ({
  ...entry,
  id: String(entry.id || ''),
  kind: entry.kind || 'uncertainty',
  by: String(entry.by || ''),
  what: String(entry.what || ''),
  date: entry.date || today(),
  links: Array.isArray(entry.links) ? entry.links.map(String) : [],
  evidence: Array.isArray(entry.evidence) ? entry.evidence.map(String) : [],
  verified_by_human: entry.verified_by_human ?? null,
  note: entry.note ?? null,
  history: Array.isArray(entry.history) ? entry.history : [],
});
export const normalizeFile = (file = {}, issue = file.issue) => ({ schemaVersion: 1, issue: String(issue || ''), entries: (file.entries || []).map(normalizeEntry) });
export const validateFile = (file) => validateAgainst(normalizeFile(file), schema);
export const contributionPath = (root, nid) => path.join(root, 'reports/issues', String(nid), 'contributions.json');
export function readContributions(root, nid) { try { return normalizeFile(JSON.parse(fs.readFileSync(contributionPath(root, nid), 'utf8')), nid); } catch { return normalizeFile({ entries: [] }, nid); } }
export function writeContributions(root, nid, file) {
  const normalized = normalizeFile(file, nid);
  const check = validateFile(normalized);
  if (!check.ok) throw new Error(`refusing to write contributions.json for #${nid}: ${check.errors.slice(0, 6).map((e) => `${e.path || '/'} ${e.message}`).join('; ')}`);
  const target = contributionPath(root, nid);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, `${JSON.stringify(normalized, null, 2)}\n`);
  return normalized;
}
export const nextId = (file) => `K${String(file.entries.reduce((m, e) => Math.max(m, Number(e.id.slice(1)) || 0), 0) + 1).padStart(3, '0')}`;

const linkText = (links) => (links || []).length ? ` (${links.map((u) => `[link](${u})`).join(', ')})` : '';
const cell = (s) => String(s ?? '—').replace(/\|/g, '\\|').replace(/\n/g, ' ');

export function issueMarkdown(issue, file) {
  let md = `# Contributions — #${issue}\n\nGenerated by \`node scripts/contributions.mjs list ${issue}\`; do not edit by hand. Curated, not inferred from commit authorship. Nothing here is posted automatically.\n\n`;
  if (!file.entries.length) return `${md}No contribution entries have been recorded yet. Add one with \`node scripts/contributions.mjs add ${issue} --kind human-origin --by "..." --what "..." --link <url>\`.\n`;
  for (const kind of ORDER) {
    const rows = file.entries.filter((e) => e.kind === kind);
    if (!rows.length) continue;
    md += `## ${SECTION[kind]}\n\n`;
    for (const e of rows) {
      const verified = e.verified_by_human === true ? ' — independently verified by a person' : e.verified_by_human === false ? ' — not independently verified' : '';
      md += `- **${e.by}**: ${e.what}${linkText(e.links)}${e.date ? ` (${e.date})` : ''}${verified}${e.note ? `\n  ${e.note}` : ''}\n`;
    }
    md += '\n';
  }
  return md;
}

// A short, plain-language draft for a human to edit and post. It only states entries that exist; an empty section is omitted.
export function draftMarkdown(issue, file) {
  const byKind = (k) => file.entries.filter((e) => e.kind === k);
  const names = [...new Set(byKind('human-origin').map((e) => e.by))];
  const ai = byKind('ai-addition').length + byKind('ai-test-discovery').length;
  const corrections = byKind('human-correction');
  const rejected = byKind('rejected-ai-approach');
  const uncertainties = byKind('uncertainty');
  if (!names.length) throw new Error('a contribution draft needs at least one human-origin entry; add one before drafting');
  let out = `# Contribution credit draft — #${issue}\n\nDRAFT. Edit and post as a person; this script never posts.\n\n`;
  out += `The original direction for this work came from ${names.join(', ')}.${linkText(byKind('human-origin').flatMap((e) => e.links))}\n\n`;
  if (ai) out += `AI-assisted work then extended the experiment and checked the resulting states.${ai ? ' The generated additions and test observations are recorded in the issue evidence.' : ''}\n\n`;
  if (corrections.length) out += `Human review corrected the AI-generated work: ${corrections.map((e) => `${e.by} — ${e.what}`).join('; ')}.\n\n`;
  if (rejected.length) out += `An earlier AI-generated approach was rejected: ${rejected.map((e) => e.what).join('; ')}.\n\n`;
  if (uncertainties.length) out += `Remaining uncertainties: ${uncertainties.map((e) => e.what).join('; ')}.\n\n`;
  out += 'Please edit this into your own words before posting; the contribution record remains the source of the attribution.\n';
  return out;
}
