#!/usr/bin/env python3
"""Turn the two PHPUnit JUnit logs into results.json and results.md.

Run from anywhere:
    python3 reports/issues/3155130/tests/summarize.py

Inputs: after-junit.xml and before-junit.xml in this folder (the same test file run against the
patched module and the pristine 2.0.x module). Both runs used the test patch, which is test support
and is not part of the implementation patch.
"""
import json
import pathlib
import xml.etree.ElementTree as ET

HERE = pathlib.Path(__file__).resolve().parent


def parse(name):
    root = ET.parse(HERE / f"{name}-junit.xml").getroot()
    suite = root.find("testsuite")
    cases = []
    for case in suite.findall("testcase"):
        failure = case.find("failure")
        error = case.find("error")
        message = ""
        if failure is not None:
            lines = [l.strip() for l in (failure.text or "").splitlines() if l.strip()]
            message = next((l for l in lines if "::" not in l and not l.startswith("Drupal\\")), lines[0] if lines else "")
            status = "fail"
        elif error is not None:
            lines = [l.strip() for l in (error.text or "").splitlines() if l.strip()]
            message = next((l for l in lines if "::" not in l and not l.startswith("Drupal\\")), lines[0] if lines else "")
            status = "error"
        else:
            status = "pass"
        cases.append({
            "name": case.get("name"),
            "status": status,
            "assertions": int(case.get("assertions") or 0),
            "time": float(case.get("time") or 0),
            "message": message,
        })
    return {
        "tests": int(suite.get("tests") or 0),
        "assertions": int(suite.get("assertions") or 0),
        "failures": int(suite.get("failures") or 0),
        "errors": int(suite.get("errors") or 0),
        "time": float(suite.get("time") or 0),
        "cases": cases,
    }


def main():
    after = parse("after")
    before = parse("before")
    results = {
        "issue": "3155130",
        "generatedFrom": ["after-junit.xml", "before-junit.xml"],
        "command": "ddev phpunit modules/contrib/text_with_summary/tests/src/FunctionalJavascript/TextareaWithSummaryTest.php --log-junit /var/www/html/phpunit-<side>.xml",
        "after": after,
        "before": before,
    }
    (HERE / "results.json").write_text(json.dumps(results, indent=2) + "\n")

    by_name = {c["name"]: c for c in after["cases"]}
    rows = []
    for case in before["cases"]:
        a = by_name.get(case["name"], {})
        b = "FAIL" if case["status"] != "pass" else "pass"
        av = "PASS" if a.get("status") == "pass" else (a.get("status") or "?").upper()
        rows.append(f"| `{case['name']}` | {b} | {av} |")
    md = f"""# #3155130 functional JavaScript test results

Generated by `tests/summarize.py` from the two JUnit logs in this folder.

- **After** (contributed `2.0.x` + the implementation patch): {after['tests']} tests, {after['assertions']} assertions, {after['failures']} failures, {after['errors']} errors, {after['time']:.1f}s.
- **Before** (pristine contributed `2.0.x`): {before['tests']} tests, {before['assertions']} assertions, {before['failures']} failures, {before['errors']} errors, {before['time']:.1f}s.

Both runs execute the same test file, applied as test support to both sides. The test patch is not part of the implementation patch; it is the regression test proposal.

| Test | Before | After |
|---|---|---|
{chr(10).join(rows)}

## Before failures

{chr(10).join(f'- `{c["name"]}`: {c["message"]}' for c in before["cases"] if c["status"] != "pass")}

## Notes

- Every Before failure is an expected consequence of the old behaviour: a toggle inside a label, no `aria-expanded`/`aria-controls`, repeated "Summary" names, lost focus, and the theme override text being overwritten on first load.
- `testSummaryPersistsAfterSave` fails in Before only on its final ARIA assertion; its summary-persistence assertions (known value, submitted name, value after collapse and save) pass on both sides. That is the point: the disclosure fix must not change data.
- DRAFT: these are automated results, not a person's test pass.
"""
    (HERE / "results.md").write_text(md)
    print(md)


if __name__ == "__main__":
    main()
