#!/usr/bin/env python3
"""Collect the browser-matrix runs into results.json / results.md and curate screenshots.

Run:
    python3 reports/issues/3155130/browser/summarize.py

It reads every completed run under reports/issues/3155130/playwright/ that has a results.json,
keeps the newest run for each environment tag, writes the two result files here, and copies the
screenshots named below into reports/issues/3155130/visual/.
"""
import json
import pathlib
import shutil

ROOT = pathlib.Path(__file__).resolve().parents[1]
PLAYWRIGHT = ROOT / "playwright"
OUT = pathlib.Path(__file__).resolve().parent
VISUAL = ROOT / "visual"


def tag_of(env):
    zoom = f"-zoom{env['zoom']}" if env.get("zoom") else ""
    rtl = "-rtl" if env.get("rtl") else ""
    forced = "-forced" if env.get("forcedColors") else ""
    return f"{env['browser']}-{env['colorScheme']}{forced}-{env['theme']}{rtl}{zoom}-{env['viewport']['width']}x{env['viewport']['height']}"


def side_metrics(side):
    collapsed = side.get("states", {}).get("collapsed", {})
    buttons = collapsed.get("buttons", [])
    summaries = collapsed.get("summaries", [])
    required = next((s for s in summaries if "field_required_summary" in s["name"]), {})
    return {
        "togglesInsideLabels": collapsed.get("togglesInsideLabels"),
        "buttons": len(buttons),
        "ariaExpanded": [b.get("expanded") for b in buttons],
        "controls": [b.get("controls") for b in buttons],
        "bodySummaryLabel": (buttons[0].get("summaryLabel") if buttons else None) or (summaries[0].get("label") if summaries else None),
        "requiredSummaryLabel": required.get("label"),
        "overrideText": side.get("themeOverride", {}).get("text"),
        "requiredError": side.get("required", {}).get("error"),
        "toggleImmediatelyBefore": buttons[0].get("immediatelyBefore") if buttons else None,
        "focusKeptAfterEnter": side.get("keyboard", {}).get("enter", {}).get("focusRetained"),
        "focusKeptAfterSpace": side.get("keyboard", {}).get("space", {}).get("focusRetained"),
        "persistence": side.get("persistence", {}),
        "axeCollapsed": len(side.get("axe", {}).get("collapsed", {}).get("violations", [])),
        "axeExpanded": len(side.get("axe", {}).get("expanded", {}).get("violations", [])),
        "overrideText": side.get("themeOverride", {}).get("text"),
        "jsErrors": side.get("jsErrors", []),
        "site": side.get("site"),
    }


runs = {}
for results_path in PLAYWRIGHT.glob("*/results.json"):
    try:
        data = json.loads(results_path.read_text())
    except json.JSONDecodeError:
        continue
    if "environment" not in data or "sides" not in data:
        continue
    tag = tag_of(data["environment"])
    current = runs.get(tag)
    if current is None or results_path.stat().st_mtime > current["mtime"]:
        runs[tag] = {"path": results_path.parent, "data": data, "mtime": results_path.stat().st_mtime}

items = []
for tag, run in sorted(runs.items()):
    data = run["data"]
    items.append({
        "tag": tag,
        "path": str(run["path"].relative_to(ROOT)),
        "environment": data["environment"],
        "durationMs": data.get("durationMs"),
        "before": side_metrics(data["sides"]["before"]),
        "after": side_metrics(data["sides"]["after"]),
    })

(OUT / "results.json").write_text(json.dumps({"issue": "3155130", "runs": items}, indent=2) + "\n")

def yn(value):
    return {True: "yes", False: "no", None: "n/a"}.get(value, str(value))

rows = [
    "| Run | Toggles in a label (B/A) | aria-expanded (B/A) | Focus kept after Enter (B/A) | Body summary label (B/A) | Summary kept after collapse+save (B/A) | axe (B/A) |",
    "|---|---|---|---|---|---|---|",
]
for item in items:
    b, a = item["before"], item["after"]
    rows.append(
        f"| `{item['tag']}` | {b['togglesInsideLabels']} / {a['togglesInsideLabels']} | "
        f"{len([x for x in b['ariaExpanded'] if x])} / {len([x for x in a['ariaExpanded'] if x])} | "
        f"{yn(b['focusKeptAfterEnter'])} / {yn(a['focusKeptAfterEnter'])} | "
        f"{b['bodySummaryLabel']} / {a['bodySummaryLabel']} | "
        f"{yn(b['persistence'].get('keptAfterCollapseAndSave'))} / {yn(a['persistence'].get('keptAfterCollapseAndSave'))} | "
        f"{b['axeCollapsed']}+{b['axeExpanded']} / {a['axeCollapsed']}+{a['axeExpanded']} |"
    )

md = f"""# #3155130 browser matrix

DRAFT. Chromium 159.0.8154.6, real keyboard input (Playwright keyboard), no screen reader. Generated by `browser/summarize.py` from the `results.json` of each run below.

Every run uses the same two sites (`3155130-contrib`): Before = contributed `text_with_summary` 2.0.x at `89c4282`, After = the same commit with the implementation and test patches. Core is `d29add7e` (Drupal 12.0-dev); Claro contrib 4.0.x at `474f080`.

| Run | Toggles in a label (B/A) | aria-expanded (B/A) | Focus kept after Enter (B/A) | Body summary label (B/A) | Summary kept after collapse+save (B/A) | axe (B/A) |
|---|---|---|---|---|---|---|
{chr(10).join(rows[2:])}

`axe` shows violations in the collapsed + expanded state, from `@axe-core/playwright` with WCAG 2.0/2.1/2.2 A and AA tags, scoped to the node form. Zero violations in both states does not mean the Before UI is accessible: axe does not evaluate focus loss, a button inside a label, or a textarea whose accessible name changes on activation.

## What the matrix shows

- **Before:** every toggle is inside a label (4 of 4), none has `aria-expanded` or `aria-controls`, every summary is named "Summary" (including the always-visible required summary), the control is not immediately before the summary content, Enter removes the control and drops focus to `<body>`, and the theme override text is overwritten on first load.
- **After:** no toggle is inside a label, all four have `aria-expanded` and a unique valid `aria-controls`, each summary and control name carries its field and item context, the control is immediately before the content it controls, focus stays on it after Enter and Space, and the theme override text survives toggling.
- **Data:** the typed summary, the submitted name `field_body[0][summary]`, and the value after collapsing and saving are the same on both sides.
- The same DOM/ARIA results hold in Default Admin and Claro, light and dark, forced colours, 480 px viewport, simulated RTL and 200% root font at 1600 px. The screenshots show the visual differences (below).

## Runs

{chr(10).join(f"- `{i['tag']}`: `{i['path']}` ({round((i['durationMs'] or 0) / 1000, 1)} s)" for i in items)}

## Intentional visual differences

1. The disclosure moves from inside the Body label (and, when expanded, from inside the Summary label) to one persistent position immediately before the summary content. This is required by "one persistent button, never inside a label, never moved during activation".
2. In the collapsed state it is a line above the Body label instead of inline after "Body"; in the expanded state it is above the "Summary" label instead of inline after it.
3. No colour, typography, spacing, icon, chevron, card or new CSS was added. The link-style button, parentheses and the `Drupal.theme.textEditSummaryButton` markup are unchanged. The visually hidden field/item context adds no visual difference.

See `VISUAL-DIFFERENCES.md` for the full list and the ARIA diffs in `visual/`.

## Not covered

- Real screen readers (VoiceOver, NVDA, JAWS, TalkBack).
- A person's keyboard pass. The keyboard input here is Playwright's real browser input, but a person has not reviewed it.
- Firefox and WebKit (Chromium only).
- A real RTL language pack; RTL is simulated with `dir="rtl"` on the page.
- Browser zoom: `--zoom=200` raises the root font size, which is not the same as browser zoom or a 400% reflow check. The 200% run at 1280x900 stopped at a click intercepted by the Default Admin sidebar; the same check completed at 1600x1200 (see the runs above).
- Touch input and real Windows High Contrast (forced colours are emulated by Playwright).
"""
(OUT / "results.md").write_text(md)

# Curated screenshots and tree diffs.
VISUAL.mkdir(exist_ok=True)
copy_map = {
    "chromium-light-default_admin-1280x900": ["collapsed", "expanded", "multi-value", "required-error", "theme-override"],
    "chromium-dark-default_admin-1280x900": ["collapsed", "expanded"],
    "chromium-light-forced-default_admin-1280x900": ["collapsed", "expanded"],
    "chromium-light-default_admin-480x900": ["collapsed", "expanded"],
    "chromium-light-claro-1280x900": ["collapsed", "expanded", "multi-value", "required-error", "theme-override"],
    "chromium-dark-claro-1280x900": ["collapsed", "expanded"],
    "chromium-light-forced-claro-1280x900": ["collapsed", "expanded"],
    "chromium-light-default_admin-rtl-1280x900": ["collapsed", "expanded"],
    "chromium-light-default_admin-zoom200-1600x1200": ["collapsed", "expanded"],
    "chromium-light-claro-zoom200-1600x1200": ["collapsed", "expanded"],
}
for item in items:
    tag = item["tag"]
    if tag not in copy_map:
        continue
    for state in copy_map[tag]:
        for side in ["before", "after"]:
            src = ROOT / item["path"] / side / f"{state}.png"
            if src.exists():
                shutil.copyfile(src, VISUAL / f"{tag}-{state}-{side}.png")
    for diff in ["aria-collapsed.diff", "aria-expanded.diff"]:
        src = ROOT / item["path"] / diff
        if src.exists() and tag in ("chromium-light-default_admin-1280x900", "chromium-light-claro-1280x900"):
            shutil.copyfile(src, VISUAL / f"{tag}-{diff}")

print(md)
