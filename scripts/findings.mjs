// A log of accessibility barriers spotted while testing an issue but outside its question: things axe, Guidepup, a keyboard pass or
// reading the code turned up that others may have missed. Each can become its own drupal.org issue once a person has confirmed it.
// Kept in reports/findings/findings.json; reports/findings/README.md is generated from it. Nothing is posted anywhere.
//   node scripts/findings.mjs add --issue <nid> --where "<page or component>" --what "<the barrier, for whom>" --source <axe|guidepup|keyboard|manual|code>
//                                 [--wcag <criterion>] [--evidence <path or URL>] [--file <path:line>]
//   node scripts/findings.mjs from-run <run folder>    candidates from a run's axe results: violations present on BEFORE exist in core
//                                                      without the patch, so they are logged; AFTER-only ones are possible regressions of the
//                                                      patch and are printed for that issue's EVIDENCE.md instead
//   node scripts/findings.mjs set <id> --status <unconfirmed|confirmed|reported|not-a-barrier|duplicate> [--link <url>] [--note "<text>"]
//   node scripts/findings.mjs list                     regenerate and print the README
// Every new entry is "unconfirmed": automated output is a lead, not a verdict.
import fs from 'node:fs';
import path from 'node:path';
import { labRoot } from '../tools/compare/lib.mjs';

// LAB_FINDINGS_DIR is for tests only.
const dir = process.env.LAB_FINDINGS_DIR ? path.resolve(process.env.LAB_FINDINGS_DIR) : path.join(labRoot, 'reports/findings');
const file = path.join(dir, 'findings.json');
const args = process.argv.slice(2); const [cmd, arg1] = args.filter((a, i) => !a.startsWith('--') && !(args[i - 1] || '').startsWith('--'));
const val = (n) => { const i = args.indexOf(`--${n}`); return i >= 0 && args[i + 1] && !args[i + 1].startsWith('--') ? args[i + 1] : null; };
const STATUSES = ['unconfirmed', 'confirmed', 'reported', 'not-a-barrier', 'duplicate'];
const SOURCES = ['axe', 'guidepup', 'keyboard', 'manual', 'code'];
const load = () => (fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')) : []);
const today = new Date().toISOString().slice(0, 10);
const nextId = (all) => `F${String(all.reduce((m, f) => Math.max(m, Number(f.id.slice(1)) || 0), 0) + 1).padStart(3, '0')}`;
const usage = () => { console.error('usage: node scripts/findings.mjs add --issue <nid> --where "<where>" --what "<barrier>" --source <axe|guidepup|keyboard|manual|code> [--wcag X] [--evidence P] [--file P:L]\n       node scripts/findings.mjs from-run <run folder> | set <id> --status <status> [--link URL] [--note TEXT] | list'); process.exit(2); };

function save(all) {
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(file, JSON.stringify(all, null, 2) + '\n');
  const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
  let md = `# Findings: barriers spotted outside the issue being tested\n\nGenerated by \`node scripts/findings.mjs list\` from \`findings.json\`; do not edit by hand.\nEach entry is a lead until a person confirms it. Nothing here has been posted to drupal.org unless the status is **reported** with a link.\n`;
  for (const st of STATUSES) {
    const rows = all.filter((f) => f.status === st); if (!rows.length) continue;
    md += `\n## ${st} (${rows.length})\n\n| Id | Found | While testing | Where | What | Source | WCAG | Evidence |\n|---|---|---|---|---|---|---|---|\n`;
    for (const f of rows) md += `| ${f.id} | ${f.found} | #${f.issue} | ${cell(f.where)} | ${cell(f.what)}${f.note ? ` (${cell(f.note)})` : ''} | ${f.source}${f.count > 1 ? ` (seen ${f.count}x)` : ''} | ${cell(f.wcag || '')} | ${cell([f.evidence, f.file, f.link].filter(Boolean).join(' · '))} |\n`;
  }
  if (!all.length) md += '\nNo findings yet.\n';
  fs.writeFileSync(path.join(dir, 'README.md'), md);
  return md;
}

const all = load();
if (cmd === 'add') {
  const issue = val('issue'), where = val('where'), what = val('what'), source = val('source');
  if (!issue || !where || !what || !SOURCES.includes(source)) usage();
  const f = { id: nextId(all), found: today, issue, where, what, source, wcag: val('wcag'), evidence: val('evidence'), file: val('file'), status: 'unconfirmed', count: 1 };
  all.push(f); save(all); console.log(`Added ${f.id} (unconfirmed). See reports/findings/README.md`);
} else if (cmd === 'from-run') {
  if (!arg1) usage();
  const rf = [path.join(path.resolve(arg1), 'results.json'), path.join(labRoot, arg1, 'results.json')].find((p) => fs.existsSync(p));
  if (!rf) { console.error(`No results.json in ${arg1}`); process.exit(1); }
  const r = JSON.parse(fs.readFileSync(rf, 'utf8'));
  const runRel = path.relative(labRoot, path.dirname(rf));
  // Any axe result recorded on a side (lab-run.mjs saves violations with their nodes); older runs only have rule counts.
  const axeOf = (s) => Object.values(s || {}).filter((x) => x && typeof x === 'object' && Array.isArray(x.violations));
  const nodes = (side) => axeOf(r.sides?.[side]).flatMap((a) => a.violations.flatMap((v) => v.nodes.map((n) => ({ key: `${v.id}|${n.target}|${a.url || ''}`, v, n, url: a.url }))));
  const before = nodes('before'), after = nodes('after'), beforeKeys = new Set(before.map((x) => x.key));
  if (!axeOf(r.sides?.before).length && !axeOf(r.sides?.after).length) { console.log('This run has no detailed axe results (older format, or no scan); nothing to harvest.'); process.exit(0); }
  let added = 0, seen = 0;
  for (const x of before) {
    const where = `${x.url || '(page)'} ${x.n.target}`;
    const old = all.find((f) => f.source === 'axe' && f.key === x.key);
    if (old) { old.count = (old.count || 1) + 1; seen++; continue; }
    all.push({ id: nextId(all), found: today, issue: r.issue, where, what: `${x.v.help} (axe ${x.v.id}, ${x.v.impact})`, source: 'axe', wcag: x.v.tags.join(', ') || null, evidence: runRel, status: 'unconfirmed', count: 1, key: x.key });
    added++;
  }
  save(all);
  const afterOnly = after.filter((x) => !beforeKeys.has(x.key));
  console.log(`From ${runRel}: ${added} new finding(s), ${seen} already logged (count raised).`);
  if (afterOnly.length) { console.log(`\n${afterOnly.length} violation(s) appear only WITH the patch. They are not logged here: they belong in reports/issues/${r.issue}/EVIDENCE.md as possible regressions:`); for (const x of afterOnly) console.log(`  - ${x.v.id} at ${x.url} ${x.n.target}: ${x.v.help}`); }
} else if (cmd === 'set') {
  const f = all.find((x) => x.id === arg1); const st = val('status');
  if (!f || (st && !STATUSES.includes(st))) { console.error(f ? `--status must be one of ${STATUSES.join(', ')}` : `no finding ${arg1}`); process.exit(2); }
  if (st) f.status = st; if (val('link')) f.link = val('link'); if (val('note')) f.note = val('note');
  if (f.status === 'reported' && !f.link) { console.error('A reported finding needs --link <the drupal.org issue>.'); process.exit(2); }
  save(all); console.log(`${f.id}: ${f.status}${f.link ? ` ${f.link}` : ''}`);
} else if (cmd === 'list') {
  process.stdout.write(save(all));
} else usage();
