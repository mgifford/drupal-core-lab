/**
 * Generate a test script based on issue information.
 */
function generateTestScript(issue: IssueInfo): string {
  const affectedPagesList = issue.affectedPages
    .map(p => `'${p}'`)
    .join(',\n    ');

  const expectedFixesList = issue.expectedFixes
    .map(f => `'${f}'`)
    .join(',\n    ');

  return `/**
 * Auto-generated test for Drupal issue #${issue.nid}.
 *
 * Issue: ${issue.title}
 * URL: https://www.drupal.org/project/drupal/issues/${issue.nid}
 *
 * This test validates that the accessibility issue described in the
 * Drupal issue is fixed. It uses the virtual screen reader to check
 * that form elements have proper accessible names.
 *
 * Generated by: validate-patch.js
 * Date: ${new Date().toISOString()}
 */
import { test, expect } from '@playwright/test';
import { AUTH_STATE_FILE } from '../lib/auth-setup';
import { injectVirtualSR, getSpokenPhraseLog, analyzeVirtualSR } from '../lib/virtual-sr';

const AFFECTED_PAGES = [
  ${affectedPagesList}
];

const EXPECTED_FIXES = [
  ${expectedFixesList}
];

test.describe('Issue #${issue.nid} - ${issue.title}', () => {
  test.use({ storageState: AUTH_STATE_FILE });

  for (const pagePath of AFFECTED_PAGES) {
    test(\`validates accessibility on \${pagePath}\`, async ({ page }) => {
      await page.goto(pagePath, { waitUntil: 'domcontentloaded' });
      await page.waitForSelector('main', { timeout: 10000 });

      // Inject virtual SR and collect spoken phrases
      await injectVirtualSR(page);
      await page.waitForTimeout(1500);
      const log = await getSpokenPhraseLog(page);

      // Analyze for accessibility issues
      const findings = analyzeVirtualSR(log);

      // Check for expected fixes
      const issues = findings.filter(f => EXPECTED_FIXES.includes(f.rule));

      // Log results
      console.log(\`\\n[Issue #${issue.nid}] page=\${pagePath}\`);
      console.log(\`[Issue #${issue.nid}] spoken phrases=\${log.length}\`);
      console.log(\`[Issue #${issue.nid}] findings=\${findings.length}\`);
      console.log(\`[Issue #${issue.nid}] expected issues=\${issues.length}\`);

      if (issues.length > 0) {
        console.log(\`[Issue #${issue.nid}] issues found:\`);
        issues.forEach(issue => {
          console.log(\`  - \${issue.severity}:\${issue.rule} at position \${issue.position}\`);
          console.log(\`    phrase: "\${issue.phrase}"\`);
        });
      }

      // Test passes if no expected issues are found
      expect(
        issues,
        \`Found \${issues.length} expected accessibility issues on \${pagePath}\`
      ).toEqual([]);
    });
  }

  test('provides detailed report', async ({ page }) => {
    const report: any = {
      issue: {
        nid: '${issue.nid}',
        title: '${issue.title}',
        url: 'https://www.drupal.org/project/drupal/issues/${issue.nid}',
      },
      timestamp: new Date().toISOString(),
      results: [],
    };

    for (const pagePath of AFFECTED_PAGES) {
      await page.goto(pagePath, { waitUntil: 'domcontentloaded' });
      await page.waitForSelector('main', { timeout: 10000 });

      await injectVirtualSR(page);
      await page.waitForTimeout(1500);
      const log = await getSpokenPhraseLog(page);
      const findings = analyzeVirtualSR(log);

      report.results.push({
        page: pagePath,
        spokenPhrases: log.length,
        findings: findings,
        hasExpectedIssues: findings.some(f => EXPECTED_FIXES.includes(f.rule)),
      });
    }

    // Write report to file
    const reportPath = path.join(OUTPUT_DIR, \`issue-\${issue.nid}-report.json\`);
    fs.mkdirSync(OUTPUT_DIR, { recursive: true });
    fs.writeFileSync(reportPath, JSON.stringify(report, null, 2));
    console.log(\`\\nReport written to: \${reportPath}\`);

    // All pages should pass
    const failedPages = report.results.filter((r: any) => r.hasExpectedIssues);
    expect(failedPages, \`Failed pages: \${failedPages.map((p: any) => p.page).join(', ')}\`).toEqual([]);
  });
});
`;
}

/**
 * Save the generated test script.
 */
function saveTestScript(issue: IssueInfo, script: string): string {
  const filename = `a11y-issue-${issue.nid}.spec.ts`;
  const filepath = path.resolve(__dirname, `../tests/${filename}`);

  fs.writeFileSync(filepath, script);
  console.log(`Test script saved to: ${filepath}`);

  return filepath;
}

