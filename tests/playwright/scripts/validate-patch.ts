// ── Main ─────────────────────────────────────────────────────────────────────

async function main() {
  const args = process.argv.slice(2);
  if (args.length === 0) {
    console.log('Usage: node validate-patch.js <issue-url>');
    console.log('');
    console.log('Example:');
    console.log('  node validate-patch.js https://www.drupal.org/project/drupal/issues/2608212');
    process.exit(1);
  }

  const issueUrl = args[0];

  try {
    // Fetch issue information
    const issue = await fetchIssueInfo(issueUrl);

    console.log('\n=== Issue Information ===');
    console.log(`NID: ${issue.nid}`);
    console.log(`Title: ${issue.title}`);
    console.log(`Affected Pages: ${issue.affectedPages.join(', ')}`);
    console.log(`Expected Fixes: ${issue.expectedFixes.join(', ')}`);

    // Generate test script
    const testScript = generateTestScript(issue);

    // Save test script
    const testPath = saveTestScript(issue, testScript);

    // Run the test
    await runTest(testPath);

    console.log('\n=== Next Steps ===');
    console.log('1. Review the generated test script');
    console.log('2. Run the test to validate the patch');
    console.log('3. Check the report for any remaining issues');

  } catch (error) {
    console.error('Error:', error);
    process.exit(1);
  }
}

// Run if executed directly
if (require.main === module) {
  main();
}

